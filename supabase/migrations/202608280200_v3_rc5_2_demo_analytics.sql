create or replace function public.platform_system_check()
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  result jsonb;
  v_demo_enabled boolean := true;
  v_duration integer := 30;
  v_warning integer := 7;
  v_cron_exists boolean := false;
  v_cron_active boolean := false;
  v_cron_schedule text := null;
  v_analytics_ready boolean := false;
begin
  if not public.is_platform_admin() then
    raise exception 'Acesso restrito ao Admin Master.' using errcode='42501';
  end if;

  select coalesce(demo_enabled,true),demo_duration_days,demo_warning_days
    into v_demo_enabled,v_duration,v_warning
  from public.platform_settings where id=1;

  v_analytics_ready :=
    to_regclass('public.analytics_events') is not null
    and to_regprocedure('public.track_public_event_v3(uuid,uuid,text,uuid)') is not null
    and to_regprocedure('public.get_store_analytics_v3(uuid,timestamptz,timestamptz)') is not null;

  if to_regnamespace('cron') is not null then
    begin
      execute $q$
        select
          exists(select 1 from cron.job where jobname='floriweb-expire-demo-trials'),
          coalesce((select active from cron.job where jobname='floriweb-expire-demo-trials' order by jobid desc limit 1),false),
          (select schedule from cron.job where jobname='floriweb-expire-demo-trials' order by jobid desc limit 1)
      $q$ into v_cron_exists,v_cron_active,v_cron_schedule;
    exception when others then
      -- Nao derruba o diagnostico inteiro se a extensao restringir leitura de cron.job.
      v_cron_exists := false;
      v_cron_active := false;
      v_cron_schedule := null;
    end;
  end if;

  select jsonb_build_object(
    'version', '3.0.0-rc.5.2',
    'platformAdmin', true,
    'stores', (select count(*) from public.stores where archived_at is null),
    'storesOnline', (select count(*) from public.stores where archived_at is null and public.store_accessible(id)),
    'storesSuspended', (select count(*) from public.stores where archived_at is null and not public.store_accessible(id)),
    'plans', (select count(*) from public.plans),
    'subscriptions', (select count(*) from public.store_subscriptions),
    'users', (select count(*) from public.store_users),
    'products', (select count(*) from public.products),
    'orders', (select count(*) from public.orders),
    'deliveryZones', (select count(*) from public.delivery_zones),
    'domains', (select count(*) from public.store_domains),
    'analyticsEvents', case when to_regclass('public.analytics_events') is not null then (select count(*) from public.analytics_events) else 0 end,
    'analyticsReady', v_analytics_ready,
    'demoEnabled', v_demo_enabled,
    'demoTrials', (
      select count(*) from public.store_subscriptions ss
      join public.plans p on p.id=ss.plan_id
      where p.code='DEMO' and ss.status='trial'
    ),
    'demoTrialsExpiringSoon', (
      select count(*) from public.store_subscriptions ss
      join public.plans p on p.id=ss.plan_id
      where p.code='DEMO' and ss.status='trial' and ss.expires_at is not null
        and ss.expires_at > now()
        and ss.expires_at <= now() + make_interval(days => v_warning)
    ),
    'demoDurationDays', v_duration,
    'demoWarningDays', v_warning,
    'demoCronScheduled', v_cron_exists and v_cron_active,
    'demoCronExists', v_cron_exists,
    'demoCronActive', v_cron_active,
    'demoCronSchedule', v_cron_schedule
  ) into result;

  return result;
end;
$$;

revoke all on function public.platform_system_check() from public;
grant execute on function public.platform_system_check() to authenticated;

