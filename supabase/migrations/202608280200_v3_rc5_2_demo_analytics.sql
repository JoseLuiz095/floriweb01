create or replace function private.enforce_demo_plan_availability()
returns trigger
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare
  v_demo_enabled boolean := true;
  v_new_plan_code text;
  v_old_plan_code text;
begin
  select p.code into v_new_plan_code
  from public.plans p
  where p.id = new.plan_id;

  if v_new_plan_code = 'DEMO' then
    select coalesce(ps.demo_enabled, true)
      into v_demo_enabled
    from public.platform_settings ps
    where ps.id = 1;

    if not coalesce(v_demo_enabled, true) then
      if tg_op = 'INSERT' then
        raise exception 'O acesso Demo esta desabilitado no Admin Master.' using errcode='P0001';
      end if;

      select p.code into v_old_plan_code
      from public.plans p
      where p.id = old.plan_id;

      -- Permite manter/editar uma Demo que ja existia, mas impede converter
      -- um plano pago para Demo enquanto a oferta global estiver desabilitada.
      if v_old_plan_code is distinct from 'DEMO' then
        raise exception 'O acesso Demo esta desabilitado no Admin Master.' using errcode='P0001';
      end if;
    end if;
  end if;

  return new;
end;
$$;

revoke all on function private.enforce_demo_plan_availability() from public, anon, authenticated;

drop trigger if exists store_subscriptions_demo_availability_trg on public.store_subscriptions;
create trigger store_subscriptions_demo_availability_trg
before insert or update of plan_id on public.store_subscriptions
for each row execute function private.enforce_demo_plan_availability();

