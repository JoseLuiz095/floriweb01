ok('Vitrine publica nao mostra suporte da plataforma',!storeLayout.includes('PlatformHelpButton'));
ok('Admin autenticado possui ajuda interna',adminLayout.includes('PlatformHelpButton'));
ok('Master autenticado possui ajuda interna',masterLayout.includes('PlatformHelpButton'));
ok('Login Admin usa Turnstile',adminLogin.includes('action="login"')&&adminLogin.includes('captchaToken'));
ok('Login Master usa Turnstile',masterLogin.includes('action="login"')&&masterLogin.includes('captchaToken'));
ok('Auth encaminha captcha ao Supabase',auth.includes('captchaToken?: string')&&auth.includes('options: captchaToken ? { captchaToken } : undefined'));
ok('Landing RPC nao tipa telefones publicos',!billing.includes('marketingWhatsapp: data.')&&!billing.includes('supportWhatsapp: data.'));
ok('Contato publico valida Turnstile',edge.includes("result.action&&result.action!=='marketing'")&&edge.includes('TURNSTILE_SECRET_KEY'));
ok('Contato publico possui rate limit',edge.includes('enforce_public_contact_rate_limit_v1')&&migration.includes('TOO_MANY_CONTACT_ATTEMPTS'));
const publicLandingSql=migration.slice(0,migration.indexOf('create or replace function public.get_admin_support_contact_v1'));
ok('Landing publica nao retorna telefones',publicLandingSql.includes("'contact_protected',true")&&!publicLandingSql.includes("'marketing_whatsapp',")&&!publicLandingSql.includes("'support_whatsapp',")&&!publicLandingSql.includes("'billing_whatsapp',"));
ok('Config publica somente a Edge publica sem JWT',config.includes('[functions.flori-public-contact]')&&config.includes('verify_jwt = false'));
ok('CSS RC6.3 aplicado',css.includes('FloriWeb V3 RC6.3: contato protegido'));
ok('Favicon Flori distinto presente',exists('public/favicon.svg')&&read('public/favicon.svg').includes('#7d273d'));
if(failures.length){console.error(`\n${failures.length} falha(s):`);failures.forEach(f=>console.error(`- ${f}`));process.exit(1)}
console.log(`\nFloriWeb RC6.3: ${checks.length}/${checks.length} verificacoes aprovadas.`);
