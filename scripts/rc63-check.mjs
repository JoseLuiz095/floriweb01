import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
const exists=(p)=>fs.existsSync(path.join(root,p));
const checks=[];const failures=[];const ok=(name,condition)=>{checks.push(name);console.log(`${condition?'OK  ':'FAIL'} ${name}`);if(!condition)failures.push(name)};
const landing=read('src/pages/store/Landing.tsx');
const storeLayout=read('src/layouts/StoreLayout.tsx');
const adminLayout=read('src/layouts/AdminLayout.tsx');
const masterLayout=read('src/layouts/MasterLayout.tsx');
const adminLogin=read('src/pages/admin/Login.tsx');
const masterLogin=read('src/pages/master/Login.tsx');
const auth=read('src/contexts/AuthContext.tsx');
const billing=read('src/services/billingFinanceApi.ts');
const edge=read('supabase/functions/flori-public-contact/index.ts');
const migration=read('supabase/migrations/202609031700_floriweb_rc6_3_public_security.sql');
const config=read('supabase/config.toml');
const css=read('src/styles.css');
ok('Landing usa contato protegido',landing.includes('ProtectedContactButton')&&landing.includes('contactProtected'));
ok('Landing nao expoe wa.me',!landing.includes('wa.me/'));
